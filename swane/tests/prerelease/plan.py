def _skip_if_pointless(item: ResolvedPass, caps) -> None:
    for capability in _PASS_REQUIREMENTS.get(item.name, ()):
        if not caps.has(capability):
            item.skipped = True
            item.skip_reason = "needs %s: %s" % (capability, caps.reason(capability))
            return


# --------------------------------------------------------------------------- #
# Coverage self-check
# --------------------------------------------------------------------------- #
@dataclass
class AxisCoverage:
    axis: Axis
    covered: dict = field(default_factory=dict)  # value -> [pass names]
    unreachable: dict = field(default_factory=dict)  # value -> reason
    deferred: dict = field(default_factory=dict)  # value -> reason a pass skipped

    @property
    def missing(self) -> list:
        """Values no pass sets at all — a genuine hole in the plan."""
        return [
            v
            for v in self.axis.values
            if v not in self.covered
            and v not in self.unreachable
            and v not in self.deferred
        ]


def coverage(plan: list, caps) -> dict:
    """Report, per axis, which values the plan exercises and which it does not.

    A value can be absent for three very different reasons, and conflating
    them would hide real bugs:

    * **unreachable** - the host cannot run it (missing capability, with the
      reason attached);
    * **deferred** - a pass *does* set it, but that pass was skipped in this
      run (typically the opt-in recon-all passes);
    * **missing** - no pass sets it anywhere. This one is a bug in the plan,
      and the only one worth failing over.
    """
    report = {axis.name: AxisCoverage(axis=axis) for axis in AXES}

    for axis in AXES:
        for value in axis.values:
            gate = axis.gate_for(value)
            if gate and not caps.has(gate):
                report[axis.name].unreachable[value] = "%s: %s" % (
                    gate,
                    caps.reason(gate),
                )

    def relevant(item, axis):
        # Only claim coverage if the pass actually loads the relevant input.
        return axis.needs_input is None or axis.needs_input in item.inputs

    # Running passes first: a value covered by any of them is covered, full
    # stop, even if some *other* (skipped) pass also happened to set it.
    for item in plan:
        if item.skipped:
            continue
        for axis_name, value in item.values.items():
            if relevant(item, AXES_BY_NAME[axis_name]):
                report[axis_name].covered.setdefault(value, []).append(item.name)

    for item in plan:
        if not item.skipped:
            continue
        for axis_name, value in item.values.items():
            entry = report[axis_name]
            if not relevant(item, AXES_BY_NAME[axis_name]):
                continue
            if value in entry.covered or value in entry.unreachable:
                continue
            entry.deferred.setdefault(value, item.skip_reason)

    return report


def describe_plan(plan: list, cover: dict) -> str:
    """A human summary of what will run, what will not, and why."""
    lines = []
    active = [p for p in plan if not p.skipped]
    lines.append(
        "Planned passes: %d to run, %d skipped" % (len(active), len(plan) - len(active))
    )
    for item in plan:
        if item.skipped:
            lines.append("  - %-28s SKIPPED  (%s)" % (item.name, item.skip_reason))
            continue
        inputs = ", ".join(str(i) for i in item.inputs)
        lines.append("  - %-28s %s" % (item.name, inputs))
        for axis_name, wanted, used, reason in item.downgrades:
            lines.append(
                "      downgraded %s: %s -> %s (%s)" % (axis_name, wanted, used, reason)
            )

    unreachable = {name: c.unreachable for name, c in cover.items() if c.unreachable}
    if unreachable:
        lines.append("Values this host cannot exercise:")
        for name, values in sorted(unreachable.items()):
            for value, reason in values.items():
                lines.append("  - %s=%s (%s)" % (name, value, reason))

    deferred = {name: c.deferred for name, c in cover.items() if c.deferred}
    if deferred:
        lines.append("Values deferred with a skipped pass:")
        for name, values in sorted(deferred.items()):
            for value, reason in values.items():
                lines.append("  - %s=%s (%s)" % (name, value, reason))

    holes = {name: c.missing for name, c in cover.items() if c.missing}
    if holes:
        lines.append("PLAN HOLES - no pass covers these values at all:")
        for name, values in sorted(holes.items()):
            lines.append("  - %s: %s" % (name, ", ".join(map(str, values))))
    else:
        lines.append("Coverage: every reachable axis value is exercised.")
    return "\n".join(lines)


def plan_holes(cover: dict) -> dict:
    """Axis values no pass covers anywhere — always a bug in :data:`PASSES`."""
    return {name: c.missing for name, c in cover.items() if c.missing}

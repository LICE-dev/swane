# --------------------------------------------------------------------------- #
# Resolution against the host
# --------------------------------------------------------------------------- #
@dataclass
class ResolvedPass:
    """A pass with every gated value resolved against the host capabilities."""

    spec: PassSpec
    values: dict  # axis name -> value actually used
    downgrades: list = field(default_factory=list)  # (axis, wanted, used, reason)
    skipped: bool = False
    skip_reason: str = ""

    @property
    def name(self) -> str:
        return self.spec.name

    @property
    def inputs(self) -> tuple:
        return self.spec.inputs


def _safe_value(axis: Axis, wanted, caps):
    """Return the first value of ``axis`` whose gate the host satisfies."""
    for candidate in (wanted,) + tuple(axis.values):
        gate = axis.gate_for(candidate)
        if not gate or caps.has(gate):
            return candidate, ""
    return None, "no usable value"


def build_plan(caps, with_reconall: bool = False, only=None) -> list:
    """Resolve every pass against the host, dropping or downgrading as needed.

    Parameters
    ----------
    caps : Capabilities
        The host probe.
    with_reconall : bool
        Include the slow FreeSurfer passes.
    only : iterable of str, optional
        Restrict to these pass names.
    """
    resolved = []
    for spec in PASSES:
        item = ResolvedPass(spec=spec, values=dict(spec.values))

        if only and spec.name not in only:
            continue
        if spec.heavy_freesurfer and not with_reconall:
            item.skipped = True
            item.skip_reason = "recon-all passes are opt-in (--with-reconall)"
            resolved.append(item)
            continue

        for axis_name, wanted in spec.values.items():
            axis = AXES_BY_NAME[axis_name]
            gate = axis.gate_for(wanted)
            if gate and not caps.has(gate):
                fallback, problem = _safe_value(axis, wanted, caps)
                if fallback is None or fallback == wanted:
                    item.skipped = True
                    item.skip_reason = "%s=%s needs %s: %s" % (
                        axis_name,
                        wanted,
                        gate,
                        caps.reason(gate),
                    )
                    break
                item.values[axis_name] = fallback
                item.downgrades.append((axis_name, wanted, fallback, caps.reason(gate)))

        # A pass whose whole reason for existing is now unavailable is skipped
        # rather than silently degraded into a duplicate of another pass.
        if not item.skipped:
            _skip_if_pointless(item, caps)
        resolved.append(item)

    return resolved


#: Passes that only make sense when a given capability is present. Public so the
#: plan-integrity test can grant every gating capability to its "capable host".

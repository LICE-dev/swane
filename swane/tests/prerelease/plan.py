"""The configuration axes to sweep, and the passes that cover them.

Running one *pass* means building and executing a whole :class:`MainWorkflow`
over the phantom exam with one coherent configuration. Because a single pass
already exercises every loaded input at once, the ~50 construction scenarios of
``nipype_pipeline/matrix`` do **not** need ~50 executions: they need a small
covering set in which every value of every axis appears at least once.

Two levers keep that set small:

* **axes that live on different inputs are swept in parallel** inside one pass
  (the resting-state MELODIC dimensionality has nothing to do with the vein
  detection mode, so they can differ in the same run);
* **each pass declares which inputs it loads**, so a pass that exists to sweep
  the diffusion axes does not also re-run the (slow, already covered) fMRI
  chain.

The passes are written out explicitly rather than generated by an algorithm:
they are meant to be read and reviewed. What *is* automatic is the guarantee
that they are complete — :func:`coverage` walks every axis value and reports
any that no enabled pass exercises, so a forgotten value shows up as a hole
instead of silently disappearing. Values that require something the host does
not have are reported as *skipped, with the reason*, never as covered.
"""

